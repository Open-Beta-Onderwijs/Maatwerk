export const ICON_CATEGORIES: IconCategory[] = RAW.map(([label, entries]) => ({
  label,
  icons: entries.map(([emoji, words]) => ({ emoji, words })),
}));

/** The default icon of a new observatie (the first of the old list). */
export const DEFAULT_OBS_ICON = '📏';

/** Lower case, without diacritics, so "bèta" finds "beta". */
function fold(s: string): string {
  return s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();
}

/**
 * The categories to show for `category` ('Alle' or a label) and the search `query` (every word
 * must start a search word or the category name; empty categories are left out).
 */
export function filterIcons(category: string, query: string): IconCategory[] {
  const terms = fold(query)
    .split(/[\s,]+/)
    .filter(Boolean);
  return ICON_CATEGORIES.filter((c) => category === 'Alle' || c.label === category)
    .map((c) => ({
      label: c.label,
      icons: c.icons.filter((i) => {
        const words = fold(`${i.words} ${c.label}`).split(/[\s&-]+/);
        return terms.every((t) => words.some((w) => w.startsWith(t)));
      }),
    }))
    .filter((c) => c.icons.length > 0);
}

/** Number of icons in the catalogue. */
export const ICON_COUNT = ICON_CATEGORIES.reduce((n, c) => n + c.icons.length, 0);
